#!/usr/bin/env bash
# Replacement for the IDCAMS/REPRO jobs: load ASCII sample data into indexed (VSAM-like) files.
set -euo pipefail
BASE="${BASE:-/opt/carddemo-env}"
SRC="${SRC:-$BASE/carddemo/app}"
DATA="$BASE/data"; mkdir -p "$DATA" "$BASE/bin" "$BASE/tmp"
FLAGS="-fsign=EBCDIC"

# gen_loader <name> <reclen> <keyoff> <keylen> [<altoff> <altlen>]
gen_loader() {
  local n=$1 rl=$2 ko=$3 kl=$4 ao=${5:-} al=${6:-}
  {
  cat <<COB
       IDENTIFICATION DIVISION.
       PROGRAM-ID. LOAD$n.
       ENVIRONMENT DIVISION.
       INPUT-OUTPUT SECTION.
       FILE-CONTROL.
           SELECT IN-FILE ASSIGN TO "INFILE"
               ORGANIZATION LINE SEQUENTIAL FILE STATUS IS IN-ST.
           SELECT OUT-FILE ASSIGN TO "OUTFILE"
               ORGANIZATION INDEXED ACCESS MODE RANDOM
               RECORD KEY IS OUT-KEY
COB
  if [ -n "$ao" ]; then echo "               ALTERNATE RECORD KEY IS OUT-ALT WITH DUPLICATES"; fi
  cat <<COB
               FILE STATUS IS OUT-ST.
       DATA DIVISION.
       FILE SECTION.
       FD IN-FILE.
       01 IN-REC PIC X($rl).
       FD OUT-FILE.
       01 OUT-REC.
COB
  # layout: [pre1] KEY [mid] [ALT] [post]; generated by position arithmetic
  local pos=1 i=0
  emit() { # emit_filler len
    if [ "$1" -gt 0 ]; then i=$((i+1)); echo "           05 FILLER$i PIC X($1)."; fi
  }
  emit $((ko-1)); echo "           05 OUT-KEY PIC X($kl)."; pos=$((ko+kl))
  if [ -n "$ao" ]; then
    emit $((ao-pos)); echo "           05 OUT-ALT PIC X($al)."; pos=$((ao+al))
  fi
  emit $((rl-pos+1))
  cat <<COB
       WORKING-STORAGE SECTION.
       01 IN-ST  PIC XX.
       01 OUT-ST PIC XX.
       01 CNT    PIC 9(7) VALUE 0.
       01 BAD    PIC 9(7) VALUE 0.
       PROCEDURE DIVISION.
           OPEN INPUT IN-FILE OUTPUT OUT-FILE
           IF IN-ST NOT = '00' OR OUT-ST NOT = '00'
              DISPLAY 'OPEN FAILED ' IN-ST ' ' OUT-ST
              MOVE 12 TO RETURN-CODE STOP RUN
           END-IF
           PERFORM UNTIL 1 = 2
              READ IN-FILE AT END EXIT PERFORM END-READ
              MOVE IN-REC TO OUT-REC
              WRITE OUT-REC
                 INVALID KEY ADD 1 TO BAD
                 NOT INVALID KEY ADD 1 TO CNT
              END-WRITE
           END-PERFORM
           CLOSE IN-FILE OUT-FILE
           DISPLAY 'LOADED $n: ' CNT ' rows, rejected ' BAD
           STOP RUN.
COB
  } > "$BASE/tmp/LOAD$n.cbl"
  cobc -x $FLAGS "$BASE/tmp/LOAD$n.cbl" -o "$BASE/bin/LOAD$n"
}

# load <name> <input.txt> <outfile> <reclen> <keyoff> <keylen> [altoff altlen]
load() {
  local n=$1 in=$2 out=$3; shift 3
  gen_loader "$n" "$@"
  tr -d '\r' < "$in" > "$BASE/tmp/$n.in"; in="$BASE/tmp/$n.in"   # normalise CRLF
  rm -f "$DATA/$out" "$DATA/$out".*
  DD_INFILE="$in" DD_OUTFILE="$DATA/$out" "$BASE/bin/LOAD$n"
}

A="$SRC/data/ASCII"
load ACCT   "$A/acctdata.txt" ACCTDATA.vsam  300 1 11
load CARD   "$A/carddata.txt" CARDDATA.vsam  150 1 16
load CUST   "$A/custdata.txt" CUSTDATA.vsam  500 1 9
load XREF   "$A/cardxref.txt" CARDXREF.vsam   50 1 16 26 11   # alt key = account id
load TCATBAL "$A/tcatbal.txt" TCATBALF.vsam   50 1 17
load DISCGRP "$A/discgrp.txt" DISCGRP.vsam    50 1 16
load TRANCATG "$A/trancatg.txt" TRANCATG.vsam 60 1 6
load TRANTYPE "$A/trantype.txt" TRANTYPE.vsam 60 1 2
: > "$BASE/tmp/empty.txt"
load TRAN   "$BASE/tmp/empty.txt" TRANSACT.vsam 350 1 16     # empty transaction master
# DALYTRAN is a fixed-length sequential file (no line breaks), as on the mainframe
tr -d '\r\n' < "$A/dailytran.txt" > "$DATA/DALYTRAN.ps"
echo "Data loaded into $DATA"
